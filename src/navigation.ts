export const titles = Object.fromEntries(screens.map(([id, title]) => [id, title])) as Record<
  Screen,
  string
>;
export function parseRoute(hash: string): { screen: Screen; id?: string } {
  const [raw, id] = hash.replace(/^#\/?/, '').split('/');
  return { screen: screens.some(([screen]) => screen === raw) ? (raw as Screen) : 'home', id };
}
